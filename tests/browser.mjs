import { chromium } from 'playwright';
import { PNG } from 'pngjs';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { load } from 'cheerio';
import {mockGroundImagery} from './imagery-fixture.mjs';

const output = 'verification';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
const results = [];
try {
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    const page = await browser.newPage({ viewport, deviceScaleFactor: 1 });
    await mockGroundImagery(page);
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
    await page.goto((process.env.TEST_BASE_URL||'http://127.0.0.1:5174')+'/?site=sinchon', { waitUntil: 'networkidle' });
    assert.equal(await page.locator('#unit-title').textContent(), '206동 504호');
    await page.waitForSelector('#outlook-host[data-ready="true"]');
    const outlook = page.locator('#outlook-host');
    const defaultBearing = Number(await outlook.getAttribute('data-bearing'));
    assert.ok(defaultBearing > 115 && defaultBearing < 140);
    assert.ok(await page.locator('#window-warning').isHidden());
    assert.ok(await page.locator('#locator-buildings polygon').count() > 3);
    assert.ok((await page.locator('#locator-arrow').getAttribute('d')).startsWith('M'));
    await outlook.scrollIntoViewIfNeeded();
    const city = PNG.sync.read(await page.locator('#outlook-host canvas').screenshot());
    let differing = 0, geometry = 0;
    const stacked = city.width < 650;
    const halfW = stacked ? city.width : Math.floor(city.width / 2);
    const halfH = stacked ? Math.floor(city.height / 2) : city.height;
    for (let y = 0; y < halfH; y++) for (let x = 0; x < halfW; x++) {
      const a = (y * city.width + x) * 4;
      const b = ((y + (stacked ? halfH : 0)) * city.width + x + (stacked ? 0 : halfW)) * 4;
      if (Math.abs(city.data[a] - city.data[b]) + Math.abs(city.data[a+1] - city.data[b+1]) > 20) differing++;
      if (city.data[a] + city.data[a+1] + city.data[a+2] < 520) geometry++;
    }
    assert.ok(differing > 1000, `different floors change scene pixels: ${differing}`);
    assert.ok(geometry > 1000, `city geometry visible: ${geometry}`);
    const heights = (await outlook.getAttribute('data-camera-heights')).split(',').map(Number);
    assert.ok(Math.abs(heights[1] - heights[0] - 14.5) < 0.01);
    await page.screenshot({ path: `${output}/outlook-${viewport.width}.png`, fullPage: true });
    const labels = page.locator('.building-label:not([hidden])');
    assert.ok(await labels.count() >= 2, 'visible surfaces have building identities');
    const firstLabel = labels.first(), buildingId = await firstLabel.getAttribute('data-building-id');
    await firstLabel.click();
    assert.ok((await page.locator('#review-building-facts').textContent()).includes(`#${buildingId}`));
    assert.equal(await page.locator('#review-building-source').getAttribute('href'), `https://www.openstreetmap.org/way/${buildingId}`);
    await page.locator('#building-labels-visible').uncheck();
    assert.equal(await labels.count(), 0);
    await page.locator('#building-labels-visible').check();
    const downloadEvent = page.waitForEvent('download');
    await page.locator('#review-kml').click();
    const download = await downloadEvent;
    const kmlPath = `${output}/model-review-${viewport.width}.kml`;
    await download.saveAs(kmlPath);
    const { readFile } = await import('node:fs/promises');
    const kml = load(await readFile(kmlPath,'utf8'), {xmlMode:true});
    assert.equal(kml('Camera').length, 2);
    assert.ok(kml('Polygon').length > 10 && kml('LineString').length > 10);
    assert.ok(kml('Camera altitude').toArray().every(node => Number.isFinite(Number(kml(node).text()))));
    await page.locator('#review-road').selectOption('463992436');
    const roadHref = new URL(await page.locator('#review-street').getAttribute('href'));
    assert.equal(roadHref.searchParams.get('map_action'),'pano');
    await page.locator('#review-road-focus').click();
    await outlook.scrollIntoViewIfNeeded();
    await page.screenshot({path:`${output}/road-review-${viewport.width}.png`,fullPage:true});
    await page.locator('#review-map').scrollIntoViewIfNeeded();
    await page.screenshot({path:`${output}/model-review-${viewport.width}.png`,fullPage:true});
    await page.locator('#outlook-reset').click();
    assert.ok(Number(await outlook.getAttribute('data-road-surfaces')) > 1000);
    assert.ok(Number(await outlook.getAttribute('data-facade-buildings')) > 10);
    assert.equal(await page.locator('#eye-height').inputValue(), '1.5');
    const detailed = await page.locator('#outlook-host canvas').screenshot();
    await page.locator('#facades-visible').uncheck();
    const simple = await page.locator('#outlook-host canvas').screenshot();
    assert.notDeepEqual(detailed, simple, 'facades affect rendered pixels');
    await page.locator('#facades-visible').check();
    await page.locator('#roads-visible').uncheck();
    const noRoads = await page.locator('#outlook-host canvas').screenshot();
    assert.notDeepEqual(detailed, noRoads, 'road surfaces affect rendered pixels');
    await page.locator('#roads-visible').check();
    await page.locator('#eye-height').fill('1.7');
    const raised = (await outlook.getAttribute('data-camera-heights')).split(',').map(Number);
    assert.ok(Math.abs(raised[0] - heights[0] - .2) < .01);
    await page.locator('#outlook-reset').click();
    assert.equal(await page.locator('#eye-height').inputValue(), '1.5');
    assert.equal(await outlook.getAttribute('data-landmarks'), '10');
    const landmarkOptions = await page.locator('#landmark-select option').evaluateAll(options => options.map(o => ({ value:o.value, name:o.textContent })));
    assert.equal(landmarkOptions.length, 10);
    for (const option of landmarkOptions) {
      await page.locator('#landmark-select').selectOption(option.value);
      assert.ok((await page.locator('#landmark-status').textContent()).includes('현재 모델 기준'));
      assert.ok(!(await page.locator('#landmark-status').textContent()).includes('화면 밖'), option.name);
      if (['relation/16474080','way/874639189','relation/8824257'].includes(option.value)) {
        await outlook.scrollIntoViewIfNeeded();
        await page.screenshot({path:`${output}/landmark-${option.value.replace('/','-')}-${viewport.width}.png`,fullPage:true});
      }
    }
    await page.locator('#landmark-select').selectOption('relation/16474080');
    const landmarkPixels = await page.locator('#outlook-host canvas').screenshot();
    await page.locator('#landmarks-visible').uncheck();
    const noLandmarkPixels = await page.locator('#outlook-host canvas').screenshot();
    assert.notDeepEqual(landmarkPixels, noLandmarkPixels, 'landmark geometry changes actual canvas pixels');
    assert.ok(await page.locator('#landmark-pin-0').isHidden());
    await page.locator('#landmarks-visible').check();
    await page.locator('#outlook-reset').click();
    await page.locator('#floor-b').selectOption('15');
    assert.equal(await page.locator('#label-b').textContent(), '206동 1504호');
    await page.locator('#floor-b').selectOption('10');
    const oldBearing = await outlook.getAttribute('data-bearing');
    await outlook.scrollIntoViewIfNeeded();
    const box = await outlook.boundingBox();
    await page.mouse.move(box.x + box.width * .7, box.y + 80);
    await page.mouse.down(); await page.mouse.move(box.x + box.width * .7 + 35, box.y + 85); await page.mouse.up();
    assert.notEqual(await outlook.getAttribute('data-bearing'), oldBearing);
    await page.locator('#outlook-reset').click();
    assert.equal(Number(await outlook.getAttribute('data-bearing')), defaultBearing);
    await page.locator('#locator-map').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${output}/revised-direction-${viewport.width}.png`, fullPage: true });
    await page.locator('.calibration summary').click();
    const initialXZ = await outlook.getAttribute('data-camera-x-z');
    const initialArrow = await page.locator('#locator-arrow').getAttribute('d');
    await page.locator('#window-east').fill('-5');
    await page.locator('#window-north').fill('4');
    assert.ok(await page.locator('#window-warning').isVisible(), 'inside-building calibration warning');
    assert.notEqual(await page.locator('#locator-arrow').getAttribute('d'), initialArrow);
    await page.locator('#outlook-reset').click();
    assert.ok(await page.locator('#window-warning').isHidden());
    assert.equal(await outlook.getAttribute('data-camera-x-z'), initialXZ);
    await page.locator('#floor-height').fill('3.2');
    assert.equal(await page.locator('#height-delta').textContent(), '높이 차 16.0m');
    await page.locator('#outlook-reset').click();
    await page.locator('.calibration summary').click();
    await page.getByRole('tab', { name: '3D 구조', exact: true }).click();
    const canvas = page.locator('#canvas-host canvas');
    await canvas.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${output}/desktop-or-mobile-${viewport.width}.png`, fullPage: true });
    const before = await canvas.screenshot();
    const png = PNG.sync.read(before);
    let darkPixels = 0, coloredPixels = 0;
    for (let i = 0; i < png.data.length; i += 4) {
      const [r, g, b] = png.data.subarray(i, i + 3);
      if (r + g + b < 570) darkPixels++;
      if (Math.max(r, g, b) - Math.min(r, g, b) > 18) coloredPixels++;
    }
    assert.ok(darkPixels > 500, 'scene has visible geometry');
    assert.ok(coloredPixels > 500, 'scene has material variation');
    await page.getByRole('button', { name: '확대', exact: true }).click();
    const after = await canvas.screenshot();
    assert.notDeepEqual(before, after, 'zoom changes rendered pixels');
    await page.getByRole('button', { name: '거실', exact: true }).click();
    assert.equal(await page.locator('#cut-walls').isChecked(), false);
    await page.screenshot({ path: `${output}/interior-${viewport.width}.png`, fullPage: true });
    await page.getByRole('button', { name: '전체 구조로 돌아가기' }).click();
    await page.locator('#building').selectOption('201');
    await page.locator('#unit').fill('1404');
    await page.getByRole('button', { name: '세대 조회', exact: true }).click();
    await page.waitForSelector('#selected-plan img');
    assert.match(await page.locator('#linkage-result').innerText(),/연결 타입: 84A/);
    await page.getByRole('link',{name:'연결된 데모 보기'}).click();
    await page.waitForFunction(()=>document.querySelector('#unit-title')?.textContent==='201동 1404호');
    assert.equal(await page.locator('#type-value').textContent(), '84A');
    await page.screenshot({ path: `${output}/84A-${viewport.width}.png`, fullPage: true });
    await page.locator('#unit').fill('9999');
    await page.getByRole('button', { name: '세대 조회', exact: true }).click();
    await page.waitForSelector('#linkage-result[data-status="unit-unlinked"]');
    assert.equal(await page.getByRole('link',{name:'연결된 데모 보기'}).count(),0);
    await page.goto((process.env.TEST_BASE_URL||'http://127.0.0.1:5174')+'/?site=sinchon&building=201&unit=1404',{waitUntil:'networkidle'});
    for (const type of ['59D', '84A', '84B', '84C', '84D', '84E', '109A', '109B']) {
      await page.locator(`[data-type="${type}"]`).click();
      await page.getByRole('tab', { name: '평면도', exact: true }).click();
      await page.locator('#reference-image').evaluate(img => img.decode());
      assert.ok(await page.locator('#reference-image').evaluate(img => img.naturalWidth >= 600));
    }
    await page.getByRole('tab', { name: '단지 배치', exact: true }).click();
    await page.locator('#reference-image').evaluate(img => img.decode());
    await page.getByRole('tab', { name: '전망', exact: true }).click();
    assert.ok(await page.locator('#outlook-unavailable').isVisible());
    await page.locator('#open-comparison').click();
    assert.ok(await page.locator('#comparison-content').isVisible());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no horizontal page overflow');
    const overflows = await page.locator('button, h1, h2, input').evaluateAll(elements => elements.filter(el => el.clientWidth > 0 && el.scrollWidth > el.clientWidth + 2).map(el => el.textContent));
    assert.deepEqual(overflows, [], 'control text fits');
    results.push({ viewport, darkPixels, coloredPixels, differing, geometry, heights, passed: true });
    await page.close();
  }
  assert.deepEqual(errors, []);
  await writeFile(`${output}/results.json`, JSON.stringify({ results, errors }, null, 2));
  console.log(JSON.stringify({ results, errors }, null, 2));
} finally { await browser.close(); }

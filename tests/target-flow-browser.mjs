import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mockGroundImagery} from './imagery-fixture.mjs';
import {mkdir} from 'node:fs/promises';
import {PNG} from 'pngjs';
const browser=await chromium.launch({channel:'chrome',headless:true}),base=process.env.TEST_BASE_URL||'http://127.0.0.1:5174';
await mkdir('verification',{recursive:true});
try{for(const width of [1440,390]){
  const page=await browser.newPage({viewport:{width,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));await mockGroundImagery(page);
  await page.goto(base+'/?site=catalog&address=신촌푸르지오2단지&building=206&unit=1403');
  await page.getByRole('link',{name:'집 구조 열기'}).click();
  await page.waitForFunction(()=>document.querySelector('#unit-title')?.textContent.includes('1403'));
  assert.match(await page.locator('#type-value').innerText(),/84E/);
  assert.equal(await page.locator('#scene-panel').isVisible(),true);
  await page.screenshot({path:`verification/target-sinchon-206-1403-${width}.png`});
  await page.goto(base+'/?site=sinchon&building=210&unit=305');
  await page.waitForFunction(()=>document.querySelector('#unit-title')?.textContent.includes('305'));
  assert.match(await page.locator('#type-value').innerText(),/34CT/);
  await page.getByRole('tab',{name:'평면도',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#reference-image')?.naturalWidth>0);
  assert.match(await page.locator('#reference-image').getAttribute('src'),/30737\/114078-basic/);
  await page.locator('#plan-openings g[data-window="living"]').click();
  await page.waitForSelector('#canvas-host[data-window="living"]');
  assert.equal(await page.locator('#canvas-host').getAttribute('data-model'),'sinchon-prugio/kb-114078-basic');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.goto(base+'/?site=xi&building=211&unit=1202');
  await page.waitForSelector('#outlook-host[data-interior="active"]');
  assert.equal(await page.locator('#outlook-host').getAttribute('data-official-buildings'),'22','14 Xi buildings and 8 surrounding Sinchon buildings in this scene');
  await page.goto(base+'/?site=xi&building=204&unit=102');
  await page.waitForSelector('#outlook-host[data-interior="active"]');
  assert.equal(await page.locator('#floor-a').inputValue(),'1');
  await page.waitForFunction(()=>document.querySelector('#xi-line option[value="1"]')?.disabled===true);
  assert.equal(await page.locator('#xi-line option[value="1"]').evaluate(o=>o.disabled),true,'204-101 is absent, not a selectable neighboring home');
  await page.goto(base+'/?site=xi&building=211&unit=101');
  await page.waitForSelector('#outlook-host[data-interior="active"]');
  assert.equal(await page.locator('#floor-a').inputValue(),'1');
  const pixels=PNG.sync.read(await page.locator('#outlook-host canvas').screenshot());
  assert.ok(new Set(pixels.data).size>60,'first-floor scene is nonblank');
  await page.screenshot({path:`verification/target-official-xi-${width}.png`});
  assert.deepEqual(errors,[]);await page.close();
}console.log('Target flow: all-source scene lookup samples, provider-only plan, official Xi heights, PC/mobile passed');}finally{await browser.close();}
